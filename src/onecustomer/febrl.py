"""Public benchmark: FEBRL4, run through the same matcher, with Splink as a baseline.

FEBRL4 (Christen, Freely Extensible Biomedical Record Linkage) is two files of 5,000 synthetic
Australian person records. Each record in file B is a corrupted copy of one record in file A, so
there are exactly 5,000 true links. It ships with the ``recordlinkage`` package, so the benchmark
runs offline. It was not generated by this repository and its corruption model is not the one the
matcher was designed around, which is the point of running it.

What changes for FEBRL4, and only this: the column mapping (below) and the ID scheme. FEBRL's
``soc_sec_id`` has no check digit, so IDs are never *trusted* and the cannot-link rule never fires.
Blocking, comparison levels, training, threshold and the identity guard are the defaults used on
the synthetic South African data.
"""

from __future__ import annotations

import time

import numpy as np
import pandas as pd

from .evaluate import pair_completeness, scorecard
from .match import ComparisonCache, candidate_pairs, link, train
from .standardise import standardise


def load() -> tuple[pd.DataFrame, np.ndarray]:
    """FEBRL4 as a single frame of records in onecustomer's input layout, plus the true entity per row."""
    from recordlinkage.datasets import load_febrl4

    a, b = load_febrl4()
    frames = []
    for system, part in (("A", a), ("B", b)):
        part = part.reset_index()
        dob = part["date_of_birth"].astype(object)
        iso = [f"{d[:4]}-{d[4:6]}-{d[6:]}" if isinstance(d, str) and len(d) == 8 and d.isdigit() else None
               for d in dob]
        street = (part["street_number"].fillna("").astype(str) + " "
                  + part["address_1"].fillna("").astype(str)).str.strip()
        frames.append(pd.DataFrame({
            "system": system,
            "record_key": part["rec_id"],
            "load_month": 1,
            "first_name": part["given_name"],
            "middle_name": None,
            "surname": part["surname"],
            "national_id": part["soc_sec_id"],
            "dob": iso,
            "phone": None,
            "email": None,
            "address_line": street.where(street != "", None),
            "city": part["suburb"],
            "postal_code": part["postcode"],
            "balance": 0.0,
        }))
    records = pd.concat(frames, ignore_index=True)
    truth = records["record_key"].str.extract(r"rec-(\d+)-")[0].astype(int).to_numpy()
    return records, truth


def run_onecustomer(records: pd.DataFrame, truth: np.ndarray, threshold: float = 0.9) -> dict:
    start = time.perf_counter()
    std = standardise(records, id_scheme="none")
    cache = ComparisonCache()
    model = train(std, cache)
    out = {"model": model.as_dict(), "rows": []}
    pairs = candidate_pairs(std)
    out["candidate_pairs"] = len(pairs)
    out["pair_completeness"] = pair_completeness(pairs["a"].to_numpy(), pairs["b"].to_numpy(), truth)
    for t in (0.5, 0.9, 0.99):
        result = link(std, "fellegi_sunter", cache=cache, model=model, threshold=t)
        out["rows"].append({"system": "onecustomer", "threshold": t, **scorecard(result.labels, truth)})
    result = link(std, "fellegi_sunter", cache=cache, model=model, threshold=threshold, identity_guard=False)
    out["rows"].append({"system": "onecustomer without identity guard", "threshold": threshold,
                        **scorecard(result.labels, truth)})
    plain = train(std, cache, tf_adjust=False)
    result = link(std, "fellegi_sunter", cache=cache, model=plain, threshold=threshold)
    out["rows"].append({"system": "onecustomer without term-frequency adjustment", "threshold": threshold,
                        **scorecard(result.labels, truth)})
    for label, strategy in (("exact ID only", "id_exact"), ("deterministic rules", "rules")):
        result = link(std, strategy, cache=cache)
        out["rows"].append({"system": f"onecustomer {label}", "threshold": None,
                            **scorecard(result.labels, truth)})
    out["seconds"] = round(time.perf_counter() - start, 1)
    return out


def run_splink(threshold: float = 0.9) -> dict:
    """Splink 5 on DuckDB as the baseline, not tuned on the labels.

    Training follows the recipe of Splink's FEBRL4 tutorial: the prior from deterministic rules with
    an assumed recall of 0.8, u by random sampling, m by EM sessions blocked on given name and on
    street number. The comparisons and blocking rules below are this repository's choice.
    """
    import splink.comparison_library as cl
    from recordlinkage.datasets import load_febrl4
    from splink import Linker, SettingsCreator, block_on
    from splink.backends.duckdb import DuckDBAPI

    start = time.perf_counter()
    a, b = load_febrl4()
    frames = []
    for part in (a, b):
        part = part.reset_index()
        part["unique_id"] = part["rec_id"]
        part = part.drop(columns=["rec_id"])
        for col in part.columns:
            part[col] = part[col].astype(object).where(part[col].notna(), None)
        frames.append(part)
    settings = SettingsCreator(
        link_type="link_only",
        unique_id_column_name="unique_id",
        comparisons=[
            cl.NameComparison("given_name"),
            cl.NameComparison("surname"),
            cl.DateOfBirthComparison("date_of_birth", input_is_string=True, datetime_format="%Y%m%d"),
            cl.DamerauLevenshteinAtThresholds("soc_sec_id", [1, 2]),
            cl.ExactMatch("street_number").configure(term_frequency_adjustments=True),
            cl.ExactMatch("postcode").configure(term_frequency_adjustments=True),
        ],
        blocking_rules_to_generate_predictions=[
            block_on("given_name", "surname"),
            block_on("surname", "date_of_birth"),
            block_on("given_name", "date_of_birth"),
            block_on("postcode", "street_number"),
            block_on("soc_sec_id"),
        ],
        retain_intermediate_calculation_columns=False,
    )
    db = DuckDBAPI()
    sdfs = [db.register(f, table_name=name) for f, name in zip(frames, ("febrl4a", "febrl4b"), strict=True)]
    linker = Linker(sdfs, settings, log_level=40)
    linker.training.estimate_probability_two_random_records_match(
        [block_on("given_name", "surname", "date_of_birth"), block_on("soc_sec_id")], recall=0.8)
    linker.training.estimate_u_using_random_sampling(max_pairs=1e6, seed=1)
    linker.training.estimate_parameters_using_expectation_maximisation(block_on("given_name"))
    linker.training.estimate_parameters_using_expectation_maximisation(block_on("street_number"))
    predictions = linker.inference.predict(threshold_match_probability=0.01)
    rows = []
    ids = pd.concat([f["unique_id"] for f in frames], ignore_index=True)
    truth = ids.str.extract(r"rec-(\d+)-")[0].astype(int).to_numpy()
    for t in (0.5, 0.9, 0.99):
        clusters = linker.clustering.cluster_pairwise_predictions_at_threshold(
            predictions, threshold_match_probability=t).as_pandas_dataframe()
        label = clusters.set_index("unique_id")["cluster_id"].reindex(ids).to_numpy()
        rows.append({"system": "Splink 5", "threshold": t, **scorecard(label, truth)})
    return {"rows": rows, "seconds": round(time.perf_counter() - start, 1)}


def benchmark(with_splink: bool = True) -> dict:
    records, truth = load()
    result = {"dataset": "FEBRL4", "records": len(records), "true_links": int(len(records) // 2)}
    result["onecustomer"] = run_onecustomer(records, truth)
    if with_splink:
        try:
            result["splink"] = run_splink()
        except ImportError:
            result["splink"] = {"skipped": "splink is not installed (pip install splink)"}
    return result


def render(result: dict) -> str:
    """Markdown table for reports/febrl4.md."""
    oc = result["onecustomer"]
    lines = [
        "# FEBRL4 benchmark",
        "",
        f"{result['records']:,} records in two files, {result['true_links']:,} true links. "
        f"onecustomer blocking produced {oc['candidate_pairs']:,} candidate pairs and kept "
        f"{100 * oc['pair_completeness']:.2f}% of true pairs (pair completeness).",
        "",
        "| System | Threshold | Precision | Recall | F1 | B-cubed F1 | Entities recovered exactly |",
        "|---|---|---|---|---|---|---|",
    ]
    rows = list(oc["rows"])
    if "rows" in result.get("splink", {}):
        rows += result["splink"]["rows"]
    for r in rows:
        t = "" if r["threshold"] is None else r["threshold"]
        lines.append(f"| {r['system']} | {t} | {100 * r['precision']:.2f}% | {100 * r['recall']:.2f}% | "
                     f"{100 * r['f1']:.2f}% | {100 * r['b3_f1']:.2f}% | {100 * r['cluster_recall']:.2f}% |")
    lines += ["", f"onecustomer run time: {oc['seconds']} s. "
              + (f"Splink run time: {result['splink']['seconds']} s." if "seconds" in result.get("splink", {})
                 else str(result.get("splink", {}).get("skipped", ""))), ""]
    return "\n".join(lines)
